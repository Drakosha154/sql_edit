-- ЗАДАНИЕ 1: Простая выборка всех данных
-- Условие: Получите список всех студентов с их именами, фамилиями и email.
-- Сложность: ★☆☆☆☆

-- Решение:
SELECT first_name, last_name, email
FROM students 


-- ЗАДАНИЕ 2: Фильтрация с условием WHERE
-- Условие: Найдите всех преподавателей, которые работают на факультете Информатики (department_id = 1).
-- Сложность: ★☆☆☆☆

-- Решение:
SELECT first_name, last_name, email
FROM teachers
WHERE department_id = 1 


-- ЗАДАНИЕ 3: Сортировка данных
-- Условие: Получите список всех курсов, отсортированных по количеству кредитов (от большего к меньшему).
-- Сложность: ★☆☆☆☆

-- Решение:
SELECT course_name, credits
FROM courses
ORDER BY credits DESC 


-- ЗАДАНИЕ 4: Подсчет количества записей
-- Условие: Подсчитайте общее количество студентов в университете.
-- Сложность: ★☆☆☆☆

-- Решение:
SELECT COUNT(*) AS total_students
FROM students 


-- ЗАДАНИЕ 5: Использование DISTINCT
-- Условие: Получите список уникальных годов поступления студентов.
-- Сложность: ★☆☆☆☆

-- Решение:
SELECT DISTINCT enrollment_year
FROM students
ORDER BY enrollment_year 


-- ЗАДАНИЕ 6: Простое условие с числовым сравнением
-- Условие: Найдите все курсы, которые дают 4 или больше кредитов.
-- Сложность: ★☆☆☆☆

-- Решение:
SELECT course_name, credits
FROM courses
WHERE credits >= 4 


-- ЗАДАНИЕ 7: Использование LIKE для поиска
-- Условие: Найдите всех студентов, чья фамилия начинается на букву "И".
-- Сложность: ★☆☆☆☆

-- Решение:
SELECT first_name, last_name
FROM students
WHERE last_name LIKE 'И%' 


-- ЗАДАНИЕ 8: Работа с датами
-- Условие: Найдите всех преподавателей, которые были приняты на работу после 2015 года.
-- Сложность: ★☆☆☆☆

-- Решение:
SELECT first_name, last_name, hire_date
FROM teachers
WHERE hire_date > '2015-12-31' 


-- ЗАДАНИЕ 9: Использование IN
-- Условие: Получите список студентов, которые учатся на факультетах с ID 1, 2 или 3.
-- Сложность: ★☆☆☆☆

-- Решение:
SELECT first_name, last_name, department_id
FROM students
WHERE department_id IN (1, 2, 3) 


-- ЗАДАНИЕ 10: Простая агрегация с GROUP BY
-- Условие: Подсчитайте количество студентов на каждом факультете.
-- Сложность: ★★☆☆☆

-- Решение:
SELECT department_id, COUNT(*) AS student_count
FROM students
GROUP BY department_id 
